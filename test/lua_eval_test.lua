require("support.beamng_stubs")
local lua_eval = require("tools.lua_eval")
local registry = require("core.registry")

test('eval tool caps serialized return and printed output',function()
  local r=assert(lua_eval.def.handler({code="print(string.rep('x',10000)); return string.rep('y',10000)",maxBytes=1024}))
  assertTrue(#jsonEncode(r)<=1024); assertTrue(r.truncated)
  local v,e=lua_eval.def.handler({code='return 1',maxBytes=0/0})
  assertNil(v); assertMatch(e,'maxBytes')
end)

test("returns the chunk's value", function()
  local res, err = lua_eval.def.handler({ code = "return 1 + 2" })
  assertNil(err)
  assertEqual(res.value, 3)
end)

test("captures printed output", function()
  local res = lua_eval.def.handler({ code = "print('hello'); print('world'); return true" })
  assertEqual(res.value, true)
  assertEqual(res.output, "hello\nworld")
end)

test("restores the real print after running", function()
  local before = print
  lua_eval.def.handler({ code = "print('x')" })
  assertEqual(print, before)
end)

test("compile error returns nil + message", function()
  local res, err = lua_eval.def.handler({ code = "this is not lua" })
  assertNil(res)
  assertMatch(err, "compile error")
end)

test("runtime error returns nil + traceback", function()
  local res, err = lua_eval.def.handler({ code = "error('boom')" })
  assertNil(res)
  assertMatch(err, "boom")
end)

test("non-string code is rejected", function()
  local res, err = lua_eval.def.handler({ code = 123 })
  assertNil(res)
  assertMatch(err, "must be a string")
end)

test("register adds it to a registry under 'lua_eval'", function()
  local r = registry.new()
  lua_eval.register(r)
  assertEqual(r:list()[1].name, "lua_eval")
end)

test("runtime error appends captured output after a separator", function()
  local res, err = lua_eval.def.handler({ code = "print('side'); error('boom')" })
  assertNil(res)
  assertMatch(err, "boom")
  assertMatch(err, "%-%-%- output %-%-%-")
  assertMatch(err, "side")
end)

test("print joins multiple args tab-separated and handles nil in the middle", function()
  local res = lua_eval.def.handler({ code = "print('a', nil, 'b'); return 1" })
  assertEqual(res.value, 1)
  assertEqual(res.output, "a\tnil\tb")
end)

test("description disambiguates GE vs VE (points at vehicle_lua_eval)", function()
  local le = require("beammcp/tools/lua_eval")
  assertMatch(le.def.description, "vehicle_lua_eval")
end)
