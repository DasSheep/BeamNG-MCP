local status = require("status")

test("fresh status: not running, zero counters, sinceLast and uptime nil", function()
  local s = status.new()
  local snap = s:snapshot()
  assertEqual(snap.running, false)
  assertEqual(snap.requestCount, 0)
  assertNil(snap.lastMethod)
  assertNil(snap.sinceLast)
  assertNil(snap.uptime)
end)

test("uptime stays nil before setServer even after ticks", function()
  local s = status.new()
  s:tick(5)
  s:tick(5)
  assertNil(s:snapshot().uptime)   -- not running yet ⇒ uptime undefined, not 10
end)

test("setServer fills host/port/toolCount and marks running; uptime starts at 0", function()
  local s = status.new()
  s:setServer("127.0.0.1", 23512, 14)
  local snap = s:snapshot()
  assertEqual(snap.running, true)
  assertEqual(snap.host, "127.0.0.1")
  assertEqual(snap.port, 23512)
  assertEqual(snap.toolCount, 14)
  assertEqual(snap.uptime, 0)
end)

test("tick advances uptime monotonically", function()
  local s = status.new()
  s:setServer("h", 1, 0)
  s:tick(1.5)
  s:tick(0.5)
  assertEqual(s:snapshot().uptime, 2)
end)

test("record bumps count, stamps method and time-of-record", function()
  local s = status.new()
  s:setServer("h", 1, 0)
  s:tick(10)
  s:record("spawn_vehicle")
  s:tick(3)
  local snap = s:snapshot()
  assertEqual(snap.requestCount, 1)
  assertEqual(snap.lastMethod, "spawn_vehicle")
  assertEqual(snap.sinceLast, 3)   -- 3s elapsed since the record at t=10
end)

test("multiple records keep the latest method and count", function()
  local s = status.new()
  s:record("a")
  s:record("b")
  local snap = s:snapshot()
  assertEqual(snap.requestCount, 2)
  assertEqual(snap.lastMethod, "b")
  assertEqual(snap.sinceLast, 0)   -- two records, no tick between ⇒ 0s since last
end)

test("setCdp updates the snapshot; defaults are inactive/0", function()
  local s = status.new()
  local snap0 = s:snapshot()
  assertTrue(snap0.cdpActive == false)
  assertEqual(snap0.cdpTargets, 0)
  s:setCdp(true, 2)
  local snap1 = s:snapshot()
  assertTrue(snap1.cdpActive == true)
  assertEqual(snap1.cdpTargets, 2)
  s:setCdp(false)
  local snap2 = s:snapshot()
  assertTrue(snap2.cdpActive == false)
  assertEqual(snap2.cdpTargets, 0)
end)

test("setMenuOpen toggles the snapshot flag; default false", function()
  local s = status.new()
  assertEqual(s:snapshot().menuOpen, false)
  s:setMenuOpen(true)
  assertEqual(s:snapshot().menuOpen, true)
  s:setMenuOpen(false)
  assertEqual(s:snapshot().menuOpen, false)
end)
